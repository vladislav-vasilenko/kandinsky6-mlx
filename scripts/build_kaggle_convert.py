def strip_module(source: str) -> str:
    """Drop the module docstring, `__future__`-free imports of project modules and the CLI `main`."""
    source = re.sub(r'\A""".*?"""\n', "", source, flags=re.DOTALL)
    source = re.sub(r"^from kandinsky6_mlx\..*\n", "", source, flags=re.MULTILINE)
    source = re.sub(r"\ndef main\(.*\Z", "\n", source, flags=re.DOTALL)
    return source.strip("\n")


def build_script() -> str:
    parts = [PREAMBLE]
    for module in MODULES:
        parts.append(f"\n# ---- {module} " + "-" * max(0, 100 - len(module)) + "\n\n")
        parts.append(strip_module((ROOT / module).read_text()) + "\n")
    parts.append(MAIN)
    return "".join(parts)


def build_metadata() -> str:
    metadata = {
        "id": KERNEL_ID,
        "title": "K6 Lite Distill MLX Convert",
        "code_file": SCRIPT.name,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [SOURCE_KERNEL],
        "model_sources": [],
    }
    return json.dumps(metadata, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    args = parser.parse_args()
    expected = {SCRIPT: build_script(), METADATA: build_metadata()}
    if args.check:
        stale = [
            str(path.relative_to(ROOT))
            for path, text in expected.items()
            if not path.is_file() or path.read_text() != text
        ]
        if stale:
            print(f"out of date: {stale}; run scripts/build_kaggle_convert.py", file=sys.stderr)
            return 1
        print("kaggle/convert is up to date")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in expected.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
