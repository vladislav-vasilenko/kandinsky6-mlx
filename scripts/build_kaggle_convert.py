def find_snapshot(root: Path = Path("/kaggle/input")) -> Path:
    # The mount path differs between notebook and script kernels, so search for the layout instead.
    for config in sorted(root.rglob("transformer/config.json")):
        candidate = config.parent.parent
        if all((candidate / name).is_dir() for name in CONVERT):
            return candidate
    raise FileNotFoundError(f"no snapshot with {CONVERT} under {root}")


