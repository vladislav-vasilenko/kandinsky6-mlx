UPLOAD = False
HF_REPO = "VVladTech/Kandinsky-6.0-Lite-distill-5s-MLX"
SOURCE_REPO = "kandinskylab/Kandinsky-6.0-Lite-distill-5s-Diffusers"
CONVERT = ("transformer", "vae", "audio_vae", "vocoder")
COPY_IF_PRESENT = ("model_index.json", "scheduler/scheduler_config.json")
OUT = Path("/kaggle/working/k6-lite-distill-mlx")


def find_snapshot(root: Path = Path("/kaggle/input")) -> Path:
    # The mount path differs between notebook and script kernels, so search for the layout instead.
    for config in sorted(root.rglob("transformer/config.json")):
        candidate = config.parent.parent
        if all((candidate / name).is_dir() for name in CONVERT):
            return candidate
    raise FileNotFoundError(f"no snapshot with {CONVERT} under {root}")


def model_card(reports: dict, revision: str | None) -> str:
    rows = "\n".join(
        f"| `{name}/model.safetensors` | {r['tensor_count']} | {r['dtype_counts']} | {r['output_bytes'] / 2**30:.2f} GiB "
        f"| `{r['output_sha256']}` |"
        for name, r in reports.items()
    )
    return f"""---
license: mit
library_name: mlx
base_model: {SOURCE_REPO}
tags: [mlx, text-to-video, text-to-audio, kandinsky]
---

# Kandinsky 6.0 Lite-distill 5s, MLX layout

Weights of [{SOURCE_REPO}](https://huggingface.co/{SOURCE_REPO}) at revision `{revision}`, converted for MLX:
convolution weights moved to channels-last layouts, the duplicate vocoder inside `audio_vae` removed, every tensor in
its stored dtype (BF16 data byte-identical). As in diffusers, DiT time embeddings and modulation run in float32: the
loader upcasts them.

Status: converted only. Parity of an MLX implementation with diffusers 0.42.1 is not established yet.

| File | Tensors | Dtypes | Size | SHA-256 |
|---|---|---|---|---|
{rows}

Text encoders are not included: `text_encoder/` is the unmodified Qwen2.5-VL-7B-Instruct, `text_encoder_2/` is CLIP-L.

License: MIT, as the source model.
"""


def run() -> None:
    import shutil

    snapshot = find_snapshot()
    revision = infer_revision(snapshot)
    free = shutil.disk_usage("/kaggle/working").free
    print(f"snapshot: {snapshot} (revision {revision}); free in /kaggle/working {free / 2**30:.1f} GiB", flush=True)
    reports = convert_checkpoint(snapshot, OUT, CONVERT, revision=revision)
    for name in COPY_IF_PRESENT:
        if (snapshot / name).is_file():
            (OUT / name).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(snapshot / name, OUT / name)
    (OUT / "README.md").write_text(model_card(reports, revision))
    summary = {name: {k: r[k] for k in ("tensor_count", "dtype_counts", "dropped_keys", "output_bytes",
                                          "output_sha256", "seconds")} for name, r in reports.items()}
    (OUT / "conversion-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2), flush=True)

    if UPLOAD:
        from huggingface_hub import HfApi
        from kaggle_secrets import UserSecretsClient

        api = HfApi(token=UserSecretsClient().get_secret("HF_TOKEN"))
        api.create_repo(HF_REPO, private=True, exist_ok=True)
        commit = api.upload_folder(repo_id=HF_REPO, folder_path=OUT, commit_message=f"Convert {SOURCE_REPO}@{revision}")
        print(f"uploaded to {HF_REPO}: {commit.oid}", flush=True)


if __name__ == "__main__":
    run()
